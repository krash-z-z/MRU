package com.example.client.gui.hud;

public final class HudBounds {
    public float x;
    public float y;
    public float width;
    public float height;

    public HudBounds(float x, float y, float width, float height) {
        this.x = x;
        this.y = y;
        this.width = width;
        this.height = height;
    }
}
